-- 功能描述: 修正历史报送数据中 4 条异常 cust_id（错误客户号 → 正确客户号）
-- 执行环境: DMS（MySQL 语法）
-- 安全口径: 每条 UPDATE 均限定 ddate（报表月份），仅修正对应月份数据，
--           不会影响该客户在其他月份的报送记录
-- 影响行数: 4 行（2025-10 两行、2025-12 一行、2026-07 一行）
